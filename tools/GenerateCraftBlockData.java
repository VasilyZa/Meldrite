import com.sun.source.tree.ClassTree;
import com.sun.source.tree.CompilationUnitTree;
import com.sun.source.tree.MemberSelectTree;
import com.sun.source.tree.MethodInvocationTree;
import com.sun.source.tree.MethodTree;
import com.sun.source.util.JavacTask;
import com.sun.source.util.TreePathScanner;
import com.sun.source.util.Trees;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeSet;
import javax.tools.ToolProvider;

/** Ports upstream generated property adapters using the exact 1.20.1 class mappings. */
public final class GenerateCraftBlockData {
    private static final String CRAFT = "org.bukkit.craftbukkit.v1_20_R1";
    private static final String GENERATED = "Generated by tools/GenerateCraftBlockData.java";
    private record Edit(int start, int end, String text) { }
    private record Source(String text, CompilationUnitTree unit, ClassTree type, Trees trees) {
        int start(com.sun.source.tree.Tree tree) { return (int) trees.getSourcePositions().getStartPosition(unit, tree); }
        int end(com.sun.source.tree.Tree tree) { return (int) trees.getSourcePositions().getEndPosition(unit, tree); }
    }

    public static void main(String[] args) throws Exception {
        if (args.length != 4) throw new IllegalArgumentException("Usage: GenerateCraftBlockData <repo> <Leaf Craft root> <Mojang mappings> <Yarn tiny>");
        Path root = Path.of(args[0]);
        Path upstream = Path.of(args[1]);
        Path target = root.resolve("versions/v1_20_1/bootstrap/src/main/java/org/bukkit/craftbukkit/v1_20_R1/block/impl");
        Map<String, String> classes = classMappings(Path.of(args[2]), Path.of(args[3]));
        List<String> skipped = new ArrayList<>();
        int generated = 0;
        try (var files = Files.list(upstream.resolve("block/impl"))) {
            for (Path file : files.filter(path -> path.toString().endsWith(".java")).sorted().toList()) {
                Path output = target.resolve(file.getFileName());
                if (Files.exists(output) && !Files.readString(output).contains(GENERATED)) continue;
                Source source = parse(file);
                List<Edit> edits = new ArrayList<>();
                TreeSet<String> unmapped = new TreeSet<>();
                new TreePathScanner<Void, Void>() {
                    @Override public Void visitMemberSelect(MemberSelectTree tree, Void unused) {
                        String name = tree.toString();
                        String mapped = classes.get(name);
                        if (mapped != null) {
                            edits.add(new Edit(source.start(tree), source.end(tree), mapped));
                            return null;
                        }
                        if (name.startsWith("org.bukkit.craftbukkit.")) {
                            edits.add(new Edit(source.start(tree), source.end(tree), name.replace("org.bukkit.craftbukkit", CRAFT)));
                            return null;
                        }
                        if (name.startsWith("net.minecraft.") && Character.isUpperCase(tree.getIdentifier().charAt(0))) {
                            unmapped.add(name);
                        }
                        return super.visitMemberSelect(tree, unused);
                    }
                }.scan(source.unit, null);
                if (!unmapped.isEmpty()) {
                    skipped.add(file.getFileName() + ": " + unmapped);
                    continue;
                }
                String nativeBlock = nativeBlockClass(source, classes);
                for (var member : source.type.getMembers()) {
                    if (member instanceof MethodTree method && method.getReturnType() == null) {
                        if (method.getParameters().isEmpty()) {
                            edits.add(new Edit(source.start(method), source.end(method), ""));
                            continue;
                        }
                        if (method.getParameters().size() != 1) continue;
                        edits.removeIf(edit -> edit.start >= source.start(method) && edit.end <= source.end(method));
                        String name = source.type.getSimpleName().toString();
                        edits.add(new Edit(source.start(method), source.end(method), "public " + name + "(net.minecraft.block.BlockState state) { this(state, null); }\n\n"
                                + "    public " + name + "(net.minecraft.block.BlockState state, java.util.Map<net.minecraft.state.property.Property<?>, Comparable<?>> parsedStates) {\n"
                                + "        super(requireBlock(state, " + nativeBlock + ".class), parsedStates);\n    }"));
                    }
                }
                StringBuilder text = new StringBuilder(source.text);
                for (Edit edit : edits.stream().sorted(Comparator.comparingInt(Edit::start).reversed()).toList()) {
                    text.replace(edit.start, edit.end, edit.text);
                }
                int headerEnd = text.indexOf("package ");
                text.replace(0, headerEnd, "/**\n * " + GENERATED + ".\n * Adapted from Leaf 1.20.1 / CraftBukkit block/impl/" + file.getFileName() + ".\n * Upstream source license: GPL-3.0, see versions/v1_20_1/bootstrap/UPSTREAM-CraftBukkit-LICENSE.txt.\n */\n");
                Files.createDirectories(output.getParent());
                Files.writeString(output, text.toString().replaceAll("(?m)^ +$", "").replaceAll("\n{3,}", "\n\n"));
                generated++;
            }
        }
        generateBindings(root, upstream, classes, target);
        Path report = root.resolve("build/reports/meldrite/block-data-generation.txt");
        Files.createDirectories(report.getParent());
        Files.writeString(report, "Generated property adapters: " + generated + "\nUnmapped upstream classes:\n" + String.join("\n", skipped) + "\n");
        Files.copy(upstream.getParent().getParent().getParent().getParent().getParent().getParent().resolve("LICENSE.txt"),
                root.resolve("versions/v1_20_1/bootstrap/UPSTREAM-CraftBukkit-LICENSE.txt"), java.nio.file.StandardCopyOption.REPLACE_EXISTING);
        System.out.println("Generated " + generated + " property adapters; unmapped " + skipped.size() + ": " + skipped);
    }

    private static String nativeBlockClass(Source source, Map<String, String> classes) {
        String[] result = {null};
        new TreePathScanner<Void, Void>() {
            @Override public Void visitMethodInvocation(MethodInvocationTree tree, Void unused) {
                if (result[0] == null && List.of("getBoolean", "getInteger", "getEnum").contains(tree.getMethodSelect().toString())
                        && !tree.getArguments().isEmpty() && tree.getArguments().get(0) instanceof MemberSelectTree literal
                        && literal.getIdentifier().contentEquals("class")) {
                    result[0] = classes.get(literal.getExpression().toString());
                }
                return super.visitMethodInvocation(tree, unused);
            }
        }.scan(source.unit, null);
        if (result[0] == null) {
            // Property-free adapters still require their registered native class.
            result[0] = "net.minecraft.block.Block";
        }
        return result[0];
    }

    private static void generateBindings(Path root, Path upstream, Map<String, String> classes, Path target) throws Exception {
        Source source = parse(upstream.resolve("block/data/CraftBlockData.java"));
        Map<String, String> bindings = new LinkedHashMap<>();
        new TreePathScanner<Void, Void>() {
            @Override public Void visitMethodInvocation(MethodInvocationTree tree, Void unused) {
                if (tree.getMethodSelect().toString().equals("register") && tree.getArguments().size() == 2) {
                    String block = tree.getArguments().get(0).toString().replace(".class", "");
                    String craft = tree.getArguments().get(1).toString().replace("::new", "");
                    String name = craft.substring(craft.lastIndexOf('.') + 1);
                    if (classes.containsKey(block) && Files.isRegularFile(target.resolve(name + ".java"))) {
                        if (bindings.put(classes.get(block), CRAFT + ".block.impl." + name) != null) {
                            throw new IllegalStateException("Duplicate native binding: " + block);
                        }
                    }
                }
                return super.visitMethodInvocation(tree, unused);
            }
        }.scan(source.unit, null);
        StringBuilder text = new StringBuilder("""
                package dev.meldrite.v1201.compat;

                import java.util.Map;
                import java.util.function.BiFunction;
                import net.minecraft.block.Block;
                import net.minecraft.block.BlockState;
                import net.minecraft.state.property.Property;
                import org.bukkit.craftbukkit.v1_20_R1.block.data.CraftBlockData;

                /** Generated by tools/GenerateCraftBlockData.java from Leaf's native block bindings. */
                public final class NativeBlockDataBindings {
                    private static final Map<Class<?>, BiFunction<BlockState, Map<Property<?>, Comparable<?>>, CraftBlockData>> BINDINGS = Map.ofEntries(
                """);
        List<String> entries = new ArrayList<>();
        bindings.forEach((block, craft) -> entries.add("        Map.entry(" + block + ".class, " + craft + "::new)"));
        text.append(String.join(",\n", entries)).append("\n    );\n\n");
        text.append("""
                    private NativeBlockDataBindings() { }
                    public static CraftBlockData create(BlockState state, Map<Property<?>, Comparable<?>> parsedStates) {
                        for (Class<?> type = state.getBlock().getClass(); type != null && Block.class.isAssignableFrom(type); type = type.getSuperclass()) {
                            var factory = BINDINGS.get(type);
                            if (factory != null) return factory.apply(state, parsedStates);
                        }
                        return null;
                    }
                }
                """);
        Files.writeString(root.resolve("versions/v1_20_1/bootstrap/src/main/java/dev/meldrite/v1201/compat/NativeBlockDataBindings.java"), text);
        System.out.println("Generated " + bindings.size() + " native block bindings");
    }

    private static Map<String, String> classMappings(Path mojang, Path yarn) throws Exception {
        Map<String, String> officialToYarn = new LinkedHashMap<>();
        List<String> tiny = Files.readAllLines(yarn);
        if (!tiny.get(0).equals("tiny\t2\t0\tofficial\tintermediary\tnamed")) throw new IllegalArgumentException("Expected official/intermediary/named Yarn tiny v2");
        for (String line : tiny) {
            String[] parts = line.split("\t");
            if (parts.length == 4 && parts[0].equals("c")) officialToYarn.put(parts[1], parts[3].replace('/', '.').replace('$', '.'));
        }
        Map<String, String> result = new LinkedHashMap<>();
        for (String line : Files.readAllLines(mojang)) {
            if (line.isEmpty() || Character.isWhitespace(line.charAt(0)) || line.startsWith("#") || !line.endsWith(":")) continue;
            String[] parts = line.substring(0, line.length() - 1).split(" -> ");
            String mapped = officialToYarn.get(parts[1]);
            if (mapped != null) result.put(parts[0].replace('$', '.'), mapped);
        }
        return result;
    }

    private static Source parse(Path path) throws Exception {
        var compiler = ToolProvider.getSystemJavaCompiler();
        try (var manager = compiler.getStandardFileManager(null, null, null)) {
            var task = (JavacTask) compiler.getTask(null, manager, null, List.of("-proc:none"), null, manager.getJavaFileObjects(path));
            CompilationUnitTree unit = task.parse().iterator().next();
            ClassTree type = (ClassTree) unit.getTypeDecls().stream().filter(ClassTree.class::isInstance).findFirst().orElseThrow();
            return new Source(Files.readString(path), unit, type, Trees.instance(task));
        }
    }
}
