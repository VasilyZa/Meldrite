import com.sun.source.tree.ClassTree;
import com.sun.source.tree.CompilationUnitTree;
import com.sun.source.tree.MemberSelectTree;
import com.sun.source.tree.MethodInvocationTree;
import com.sun.source.tree.MethodTree;
import com.sun.source.tree.VariableTree;
import com.sun.source.util.JavacTask;
import com.sun.source.util.TreePathScanner;
import com.sun.source.util.Trees;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.Map;
import java.util.Set;
import javax.lang.model.element.Modifier;
import javax.tools.ToolProvider;

/** Ports Leaf's abstract property adapters to per-instance native properties. */
public final class GenerateCraftBlockTemplates {
    private static final String CRAFT = "org.bukkit.craftbukkit.v1_20_R1";
    private static final String MARKER = "Generated by tools/GenerateCraftBlockTemplates.java";
    private static final Map<String, String> NATIVE = Map.of(
            "net.minecraft.world.level.block.state.properties.BooleanProperty", "net.minecraft.state.property.BooleanProperty",
            "net.minecraft.world.level.block.state.properties.IntegerProperty", "net.minecraft.state.property.IntProperty",
            "net.minecraft.world.level.block.state.properties.EnumProperty", "net.minecraft.state.property.EnumProperty");
    private record Edit(int start, int end, String text) { }

    public static void main(String[] args) throws Exception {
        if (args.length != 2) throw new IllegalArgumentException("Usage: GenerateCraftBlockTemplates <repo> <Leaf Craft root>");
        Path root = Path.of(args[0]);
        Path sourceRoot = Path.of(args[1]).resolve("block/data");
        Path targetRoot = root.resolve("versions/v1_20_1/bootstrap/src/main/java/" + CRAFT.replace('.', '/') + "/block/data");
        var compiler = ToolProvider.getSystemJavaCompiler();
        var probes = new StringBuilder();
        var checks = new StringBuilder();
        int count = 0;
        try (var files = Files.walk(sourceRoot); var manager = compiler.getStandardFileManager(null, null, null)) {
            for (Path file : files.filter(path -> path.toString().endsWith(".java")).sorted().toList()) {
                if (file.getFileName().toString().equals("CraftBlockData.java")) continue;
                Path target = targetRoot.resolve(sourceRoot.relativize(file));
                if (Files.exists(target) && !Files.readString(target).contains(MARKER)) continue;
                String source = Files.readString(file);
                var task = (JavacTask) compiler.getTask(null, manager, null, List.of("-proc:none"), null, manager.getJavaFileObjects(file));
                CompilationUnitTree unit = task.parse().iterator().next();
                ClassTree type = (ClassTree) unit.getTypeDecls().get(0);
                if (!type.getModifiers().getFlags().contains(Modifier.ABSTRACT)) {
                    int start = (int) Trees.instance(task).getSourcePositions().getStartPosition(unit, type);
                    if (!source.substring(start).startsWith("public class ")) throw new IllegalStateException("Not a property adapter: " + file);
                }
                Trees trees = Trees.instance(task);
                var positions = trees.getSourcePositions();
                String name = type.getSimpleName().toString();
                Set<String> fields = type.getMembers().stream().filter(VariableTree.class::isInstance)
                        .map(VariableTree.class::cast).map(field -> field.getName().toString()).collect(java.util.stream.Collectors.toSet());
                var edits = new ArrayList<Edit>();
                new TreePathScanner<Void, Void>() {
                    int start(com.sun.source.tree.Tree tree) { return (int) positions.getStartPosition(unit, tree); }
                    int end(com.sun.source.tree.Tree tree) { return (int) positions.getEndPosition(unit, tree); }
                    @Override public Void visitVariable(VariableTree tree, Void unused) {
                        if (fields.contains(tree.getName().toString()) && tree.getModifiers().getFlags().contains(Modifier.STATIC)) {
                            String modifiers = source.substring(start(tree.getModifiers()), end(tree.getModifiers()));
                            edits.add(new Edit(start(tree.getModifiers()), end(tree.getModifiers()), modifiers.replace("static ", "")));
                        }
                        return super.visitVariable(tree, unused);
                    }
                    @Override public Void visitMemberSelect(MemberSelectTree tree, Void unused) {
                        String value = tree.toString();
                        if (NATIVE.containsKey(value)) {
                            edits.add(new Edit(start(tree), end(tree), NATIVE.get(value))); return null;
                        }
                        if (tree.getExpression().toString().equals(name) && fields.contains(tree.getIdentifier().toString())) {
                            edits.add(new Edit(start(tree), end(tree), "this." + tree.getIdentifier())); return null;
                        }
                        if (value.startsWith("org.bukkit.craftbukkit.")) {
                            edits.add(new Edit(start(tree), end(tree), value.replace("org.bukkit.craftbukkit", CRAFT))); return null;
                        }
                        return super.visitMemberSelect(tree, unused);
                    }
                    @Override public Void visitMethodInvocation(MethodInvocationTree tree, Void unused) {
                        String method = tree.getMethodSelect().toString();
                        if (List.of("getBoolean", "getInteger", "getEnum").contains(method)) {
                            edits.add(new Edit(start(tree.getMethodSelect()), end(tree.getMethodSelect()), "template" + method.substring(3)));
                        }
                        return super.visitMethodInvocation(tree, unused);
                    }
                }.scan(unit, null);
                int body = source.indexOf('{', (int) positions.getStartPosition(unit, type));
                String constructors = "\n    protected " + name + "(net.minecraft.block.BlockState state) { this(state, null); }\n"
                        + "    protected " + name + "(net.minecraft.block.BlockState state, java.util.Map<net.minecraft.state.property.Property<?>, Comparable<?>> parsedStates) { super(state, parsedStates); }\n";
                edits.add(new Edit(body + 1, body + 1, constructors));
                var result = new StringBuilder(source);
                for (var edit : edits.stream().sorted(Comparator.comparingInt(Edit::start).reversed()).toList()) result.replace(edit.start(), edit.end(), edit.text());
                result.insert(0, "/**\n * " + MARKER + ".\n * Adapted from Leaf 1.20.1 / CraftBukkit block/data/" + sourceRoot.relativize(file) + ".\n * GPL-3.0; see versions/v1_20_1/bootstrap/UPSTREAM-CraftBukkit-LICENSE.txt.\n */\n");
                if (result.indexOf("net.minecraft.world.") >= 0) throw new IllegalStateException("Unmapped native reference: " + file);
                Files.createDirectories(target.getParent());
                Files.writeString(target, result);
                Path implementation;
                try (var candidates = Files.list(targetRoot.getParent().resolve("impl"))) {
                    String reference = "// org.bukkit.craftbukkit.block.data." + sourceRoot.relativize(file).toString().replace('/', '.').replace(".java", "");
                    implementation = candidates.filter(path -> path.toString().endsWith(".java")).sorted()
                            .filter(path -> {
                                try { String content = Files.readString(path); return content.contains(reference + "\n") || content.contains("// org.bukkit.craftbukkit.block.data." + name + "\n"); }
                                catch (java.io.IOException failure) { throw new java.io.UncheckedIOException(failure); }
                            }).findFirst().orElseThrow(() -> new IllegalStateException("No concrete native implementation: " + file));
                }
                String implementationSource = Files.readString(implementation);
                var implementationTask = (JavacTask) compiler.getTask(null, manager, null, List.of("-proc:none"), null, manager.getJavaFileObjects(implementation));
                CompilationUnitTree implementationUnit = implementationTask.parse().iterator().next();
                ClassTree implementationType = (ClassTree) implementationUnit.getTypeDecls().get(0);
                var implementationPositions = Trees.instance(implementationTask).getSourcePositions();
                var methods = type.getMembers().stream().filter(MethodTree.class::isInstance).map(MethodTree.class::cast)
                        .map(method -> method.getName() + ":" + method.getParameters().size()).collect(java.util.stream.Collectors.toSet());
                String probeName = "Adapter" + count;
                String adapterType = unit.getPackageName().toString().replace("org.bukkit.craftbukkit", CRAFT) + "." + name;
                String[] nativeBlock = {null};
                new TreePathScanner<Void, Void>() {
                    @Override public Void visitMethodInvocation(MethodInvocationTree tree, Void unused) {
                        if (tree.getMethodSelect().toString().equals("requireBlock") && tree.getArguments().size() == 2) nativeBlock[0] = tree.getArguments().get(1).toString();
                        return super.visitMethodInvocation(tree, unused);
                    }
                }.scan(implementationUnit, null);
                if (nativeBlock[0] == null) throw new IllegalStateException("Missing native class: " + implementation);
                checks.append("        exercise(new ").append(probeName).append("(nativeState(").append(nativeBlock[0]).append(")), ").append(adapterType).append(".class);\n");
                probes.append("    public static final class ").append(probeName).append(" extends ").append(adapterType).append(" implements ")
                        .append(implementationType.getImplementsClause().stream().map(Object::toString).collect(java.util.stream.Collectors.joining(", "))).append(" {\n")
                        .append("        public ").append(probeName).append("(net.minecraft.block.BlockState state) { super(state); }\n");
                for (var member : implementationType.getMembers()) {
                    if (member instanceof MethodTree method && (method.getReturnType() == null || methods.contains(method.getName() + ":" + method.getParameters().size()))) continue;
                    int start = (int) implementationPositions.getStartPosition(implementationUnit, member);
                    int end = (int) implementationPositions.getEndPosition(implementationUnit, member);
                    if (start < 0 || end < 0) continue;
                    probes.append(implementationSource.substring(start, end).replace(implementationType.getSimpleName() + ".", probeName + ".")).append('\n');
                }
                probes.append("    }\n");
                count++;
            }
        }
        Path probe = root.resolve("versions/v1_20_1/bootstrap/src/test/java/dev/meldrite/v1201/compat/NativeBlockTemplateBatchProbe.java");
        Files.writeString(probe, """
                package dev.meldrite.v1201.compat;

                /** Generated by tools/GenerateCraftBlockTemplates.java; runs the inherited template methods. */
                public final class NativeBlockTemplateBatchProbe {
                    private NativeBlockTemplateBatchProbe() { }
                    public static void verify() throws Exception {
                """ + checks + """
                    }
                    private static net.minecraft.block.BlockState nativeState(Class<? extends net.minecraft.block.Block> type) {
                        for (var block : net.minecraft.registry.Registries.BLOCK) if (type.isInstance(block)) return block.getDefaultState();
                        throw new AssertionError("Native block not registered: " + type);
                    }
                    private static void exercise(org.bukkit.craftbukkit.v1_20_R1.block.data.CraftBlockData data, Class<?> type) throws Exception {
                        int mutations = 0;
                        if (data instanceof org.bukkit.block.data.type.BrewingStand stand && type.getSimpleName().equals("CraftBrewingStand")) {
                            for (int slot = 0; slot < stand.getMaximumBottles(); slot++) {
                                var copy = (org.bukkit.block.data.type.BrewingStand) data.clone(); copy.setBottle(slot, !stand.hasBottle(slot));
                                if (copy.hasBottle(slot) == stand.hasBottle(slot) || !copy.getBottles().contains(slot)) throw new AssertionError("Bottle template state"); mutations++;
                            }
                        }
                        if (data instanceof org.bukkit.block.data.type.ChiseledBookshelf shelf && type.getSimpleName().equals("CraftChiseledBookshelf")) {
                            for (int slot = 0; slot < shelf.getMaximumOccupiedSlots(); slot++) {
                                var copy = (org.bukkit.block.data.type.ChiseledBookshelf) data.clone(); copy.setSlotOccupied(slot, !shelf.isSlotOccupied(slot));
                                if (copy.isSlotOccupied(slot) == shelf.isSlotOccupied(slot) || !copy.getOccupiedSlots().contains(slot)) throw new AssertionError("Bookshelf template state"); mutations++;
                            }
                        }
                        if (data instanceof org.bukkit.block.data.type.RedstoneWire wire && type.getSimpleName().equals("CraftRedstoneWire")) {
                            for (var face : wire.getAllowedFaces()) {
                                var copy = (org.bukkit.block.data.type.RedstoneWire) data.clone(); copy.setFace(face, org.bukkit.block.data.type.RedstoneWire.Connection.UP);
                                if (copy.getFace(face) != org.bukkit.block.data.type.RedstoneWire.Connection.UP || wire.getFace(face) != org.bukkit.block.data.type.RedstoneWire.Connection.NONE) throw new AssertionError("Wire template state"); mutations++;
                            }
                        }
                        if (data instanceof org.bukkit.block.data.type.Wall wall && type.getSimpleName().equals("CraftWall")) {
                            for (var face : java.util.List.of(org.bukkit.block.BlockFace.NORTH, org.bukkit.block.BlockFace.EAST, org.bukkit.block.BlockFace.SOUTH, org.bukkit.block.BlockFace.WEST)) {
                                var copy = (org.bukkit.block.data.type.Wall) data.clone(); copy.setHeight(face, org.bukkit.block.data.type.Wall.Height.TALL);
                                if (copy.getHeight(face) != org.bukkit.block.data.type.Wall.Height.TALL || wall.getHeight(face) != org.bukkit.block.data.type.Wall.Height.NONE) throw new AssertionError("Wall template state"); mutations++;
                            }
                        }
                        for (var setter : type.getDeclaredMethods()) {
                            if (!setter.getName().startsWith("set") || setter.getParameterCount() != 1) continue;
                            String suffix = setter.getName().substring(3);
                            java.lang.reflect.Method getter;
                            try { getter = type.getMethod("get" + suffix); }
                            catch (NoSuchMethodException missing) {
                                try { getter = type.getMethod("is" + suffix); }
                                catch (NoSuchMethodException alsoMissing) {
                                    try { getter = type.getMethod("has" + suffix); }
                                    catch (NoSuchMethodException absent) { continue; }
                                }
                            }
                            Class<?> parameter = setter.getParameterTypes()[0];
                            Object original = getter.invoke(data);
                            var values = new java.util.ArrayList<Object>();
                            if (parameter == boolean.class) values.add(!((Boolean) original));
                            else if (parameter == int.class) { values.add(((Integer) original) + 1); values.add(((Integer) original) - 1); }
                            else if (parameter.isEnum()) java.util.Collections.addAll(values, parameter.getEnumConstants());
                            else continue;
                            for (Object value : values) {
                                if (value.equals(original)) continue;
                                var copy = data.clone();
                                var before = copy.getState();
                                try { setter.invoke(copy, value); }
                                catch (java.lang.reflect.InvocationTargetException failure) { if (failure.getCause() instanceof IllegalArgumentException) continue; throw failure; }
                                if (!value.equals(getter.invoke(copy)) || before.equals(copy.getState()) || !before.equals(data.getState())) throw new AssertionError("Template/native mismatch: " + setter);
                                if (!copy.equals(org.bukkit.craftbukkit.v1_20_R1.block.data.CraftBlockData.newData(null, copy.getAsString()))) throw new AssertionError("Template roundtrip: " + setter);
                                mutations++; break;
                            }
                        }
                        if (type.getSimpleName().equals("CraftJukebox")) {
                            boolean record = ((org.bukkit.block.data.type.Jukebox) data).hasRecord();
                            if (record != data.getState().get(net.minecraft.block.JukeboxBlock.HAS_RECORD)) throw new AssertionError("Jukebox template state");
                            mutations++;
                        }
                        if (type.getSimpleName().equals("CraftLectern")) {
                            boolean book = ((org.bukkit.block.data.type.Lectern) data).hasBook();
                            if (book != data.getState().get(net.minecraft.block.LecternBlock.HAS_BOOK)) throw new AssertionError("Lectern template state");
                            mutations++;
                        }
                        if (mutations == 0) throw new AssertionError("No template state checks exercised: " + type);
                    }
                """ + probes + "}\n");
        System.out.println("Generated " + count + " native property templates");
    }
}
