import com.sun.source.tree.ClassTree;
import com.sun.source.tree.CompilationUnitTree;
import com.sun.source.tree.MethodTree;
import com.sun.source.util.JavacTask;
import com.sun.source.util.Trees;
import java.lang.reflect.Modifier;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import javax.tools.ToolProvider;

/** Records remaining interface gaps explicitly while preserving native implementations. */
public final class GenerateEntityApi {
    private record Source(String text, CompilationUnitTree unit, ClassTree type, Trees trees) {
        List<MethodTree> methods() { return type.getMembers().stream().filter(MethodTree.class::isInstance).map(MethodTree.class::cast).toList(); }
        String declaration(MethodTree method) { var positions = trees.getSourcePositions(); return text.substring((int) positions.getStartPosition(unit, method), (int) positions.getStartPosition(unit, method.getBody())); }
    }
    private static final String MARKER = "    // Remaining API gaps generated by tools/GenerateEntityApi.java.\n";
    public static void main(String[] args) throws Exception {
        Path root = args.length == 0 ? Path.of(".") : Path.of(args[0]);
        Path directory = root.resolve("versions/v1_20_1/bootstrap/src/main/java/org/bukkit/craftbukkit/v1_20_R1/entity");
        Source api = parse(root.resolve("adapters/paper-1.20.1/src/main/java/dev/meldrite/paper/facade/PlayerAdapter.java"));
        Set<String> inherited = new HashSet<>();
        for (Path file : List.of(directory.resolve("CraftEntity.java"), root.resolve("adapters/paper-1.20.1/src/main/java/dev/meldrite/paper/facade/EntityAdapter.java"))) parse(file).methods().forEach(method -> inherited.add(key(method)));
        for (String type : List.of("LivingEntity", "HumanEntity")) {
            Path target = directory.resolve("Craft" + type + ".java");
            String existing = Files.readString(target); int marker = existing.indexOf(MARKER);
            String prefix = marker < 0 ? existing.substring(0, existing.lastIndexOf('}')) : existing.substring(0, marker);
            Source source = parse(target); source.methods().stream().filter(method -> !method.getBody().toString().contains("UNSUPPORTED_NATIVE_")).forEach(method -> inherited.add(key(method)));
            Set<String> required = new HashSet<>();
            for (var method : Class.forName("org.bukkit.entity." + type).getMethods()) if (Modifier.isAbstract(method.getModifiers())) required.add(method.getName() + "(" + String.join(",", java.util.Arrays.stream(method.getParameterTypes()).map(Class::getCanonicalName).toList()) + ")");
            StringBuilder result = new StringBuilder(prefix).append(MARKER); int count = 0;
            for (MethodTree method : api.methods()) if (required.contains(key(method)) && !inherited.contains(key(method))) {
                result.append("    ").append(api.declaration(method).trim()).append(" { throw new UnsupportedOperationException(\"UNSUPPORTED_NATIVE_").append(type.toUpperCase(java.util.Locale.ROOT)).append("_API: ").append(key(method)).append("\"); }\n");
                inherited.add(key(method)); count++;
            }
            Files.writeString(target, result.append("}\n"));
            System.out.println("Craft" + type + " retains " + count + " explicit unsupported API gaps");
        }
    }
    private static String key(MethodTree method) { return method.getName() + "(" + String.join(",", method.getParameters().stream().map(parameter -> erase(parameter.getType().toString())).toList()) + ")"; }
    private static String erase(String type) { StringBuilder result = new StringBuilder(); int depth = 0; for (char ch : type.toCharArray()) { if (ch == '<') depth++; else if (ch == '>') depth--; else if (depth == 0) result.append(ch); } String value = result.toString().replace("...", "[]"); return value.equals("T") || value.equals("K") ? "java.lang.Object" : value; }
    private static Source parse(Path path) throws Exception { var compiler = ToolProvider.getSystemJavaCompiler(); var manager = compiler.getStandardFileManager(null, null, null); var task = (JavacTask) compiler.getTask(null, manager, null, List.of("-proc:none"), null, manager.getJavaFileObjects(path)); CompilationUnitTree unit = task.parse().iterator().next(); ClassTree type = (ClassTree) unit.getTypeDecls().stream().filter(ClassTree.class::isInstance).findFirst().orElseThrow(); return new Source(Files.readString(path), unit, type, Trees.instance(task)); }
}
